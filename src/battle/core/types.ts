// 回答形式
// ============================================================

/**
 * 対戦で使う回答形式。
 *
 * ★手打ち入力（キーボード）は1つも無い。★
 * 対戦は制限時間が短く、日本語IMEの変換確定が入ると回線やIMEの差で
 * 実力と無関係に勝敗が決まってしまうため、すべて「押すだけ」で答える。
 *
 *  - choice4 … 元データが持っている4つの選択肢から1つ選ぶ
 *  - choice  … 元データが持っている2〜3つの選択肢から1つ選ぶ
 *  - kana    … ★五十音キーボードで1文字ずつ押して用語を書く（「みんはや」方式）★
 *  - word    … 4つの語句カードから1つ選ぶ（元が短答/記述の設問を「変換」したもの）
 *  - panel   … 文字パネルを順に押して語を組み立てる（同じく「変換」したもの）
 *
 * -------------------------------------------------------------------
 * ■ kana（五十音キーボード）を入れた理由
 * -------------------------------------------------------------------
 * 選択式だけにすると、★選択肢を見れば思い出せる★ので、
 * 用語を本当に覚えているかを問えない。利用者からも
 * 「みんはやと同様な1文字ずつ押していく方式をもっと導入してほしい」
 * と指定があった。
 *
 * ★以前の文字パネル（panel）とは別の形式である★
 * panel は「答えの文字＋ダミー3枚」を並べて選ばせていたので、
 * 並んだ文字を見れば答えが絞れた（「酸」「化」があれば酸化しかない）。
 * kana は画面に何のヒントも出ない。
 *
 * ★手打ち入力（IME）ではない★
 * キーボードはアプリが描く五十音表で、押した文字がそのまま入る。
 * 変換確定が無いので、端末やIMEの差で勝敗が決まらない。
 *
 * ★出題はカタカナの用語に限定している★
 * 漢字の答え（「酸化」）は、かなで書けるとしても
 * 「さんか」なのか「酸化」なのかを一つに決められない（表記ゆれ）。
 * カタカナの用語（「ダイヤモンド」「ミトコンドリア」）は
 * 書き方が1通りに定まるので、★正しく答えたのに不正解★が起きない。
 * 実測で72件（化学基礎31・生物基礎40・化学1）ある。
 *
 * -------------------------------------------------------------------
 * ■ ★word / panel は現在1問も生成していない★
 * -------------------------------------------------------------------
 * この2つは元が短答・記述の設問を対戦向けに作り替えたものだった。
 * 誤答は「同じ章の他の設問の正解」を借りて並べていたため、
 *
 *   ・借りた誤答が、その問いに対しても実は正しい
 *   ・穴埋めのリード文を切り出す過程で前提の文が消え、答えが一意でなくなる
 *   ・文字パネルは、答えの表記ゆれ（送り仮名・カタカナ）を1つに固定できない
 *
 * という形で ★問いとして成り立たない問題★ が混ざった。
 * 利用者からも「問題が論理的に破綻している場合が多い」と指摘されたため、
 * 現在は ★元データが選択肢を持っている設問だけ★ を出題している
 * （＝対戦に出る問題は、演習で解ける問題とまったく同じ内容になる）。
 *
 * 型と形式番号は残してある。生成器（scripts/gen-battle-pool.mts）の
 * USE_SYNTHESIZED_FORMATS を true に戻せば復活するが、
 * 戻すなら上の3点を先に解決すること。
 *
 * -------------------------------------------------------------------
 * ■ choice（2〜3択）を choice4 と別に持つ理由
 * -------------------------------------------------------------------
 * 元データには「元素／単体」「高／低」「吸収／放出」のような
 * ★2つのうち正しい方を選ぶ★ 設問が実測109件ある。これは出題者が
 * 意図して2択にした本物の設問であって、選択肢が足りない不良データではない。
 *
 * ここに他の設問の答えを2つ足して4択にすると、
 * 「元素／単体／中和／モル」のように毛色の違う語が並び、
 * 消去法だけで当たる問題に化ける（＝元の設問より簡単になる）。
 * そのため ★足さずに2択のまま出す★。
 * 画面側は選択肢の数を数えて並べるので、2でも3でも4でも同じ部品で出せる。
 */
export type BattleAnswerFormat = 'choice4' | 'choice' | 'kana' | 'word' | 'panel';

/**
 * 出題1問（プールに入る単位）。
 *
 * ★単位は「小問（subQuestion）」であって大問ではない。★
 * 大問単位にすると、4択だけで構成された大問が実データにほとんど無いため
 * （化学基礎で22%、化学で0%）成立しない。小問単位なら
 * 化学基礎950・リスニング221・生物基礎202・数学138・英文法100・地理25 が使える。
 *
 * ★正解そのもの（correctAnswer）はこの型に入れない。★
 * 入れると出題プールを配るだけで答えが露出する。
 * 正解は `answerIndex`（正解の選択肢番号）または `panelOrder`（押す順）
 * という「並びの中での位置」でしか持たない。並びは生成時に固定してあるので、
 * 位置が分かっても他の問題の答えは分からない。
 *
 * ★kana 形式だけは例外で、panelOrder に★五十音キーボードのキー番号★を
 * 並べて持っている（例「ダイヤモンド」→ [57,1,35,66,24,61]）。
 * 選択肢が存在しない形式なので位置で表せないが、番号だけを見ても
 * 文字に戻すには core/kanaKeyboard.ts の番号表が必要なので、
 * プールを覚えて対戦することの難しさは他の形式と変わらない。
 */
export interface BattleQuestion {
  /** 出題ID。`{小問ID}` を基に作る、プール内で一意な文字列 */
  id: string;
  /** 教科ID（allChapters.ts の SubjectKey と同じ文字列） */
  subject: string;
  /** 章ID（どの単元から出たか。リザルト画面で「この章を復習」に使う） */
  chapterId: string;
  /** 元の大問ID（解説へ飛ぶために保持） */
  problemId: string;
  /** 元の小問ID（復習リストと突き合わせるために保持） */
  subQuestionId: string;
  /** 回答形式 */
  format: BattleAnswerFormat;
  /** 問題文（対戦用に短く整形済み） */
  prompt: string;
  /** 設問ラベル（「(ア)」「問2 (1)」など。空文字なら表示しない） */
  label: string;
  /**
   * 選択肢。
   *   choice4 / word … 必ず4つ
   *   choice         … 2つまたは3つ（元データがその数で出している設問）
   *   panel          … 押せる文字パネル（4〜8枚）
   *   kana           … ★空配列★（五十音キーボードは画面側が描くので
   *                     選択肢を持たない。もし持たせると、プールを見ただけで
   *                     答えの文字数と使う文字が分かってしまう）
   */
  options: string[];
  /**
   * 正解の選択肢番号。choice4 / choice / word のときのみ意味を持ち、
   * 0 以上 options.length 未満。panel / kana のときは -1（使わない）。
   */
  answerIndex: number;
  /**
   * 「正しく押す順番」。形式で意味が違う。
   *
   *   panel … options の添字。
   *           例: options=['素','水','酸','化'] で答えが「酸化」なら [2,3]。
   *   kana  … ★五十音キーボードのキー番号★（core/kanaKeyboard.ts の KANA_KEYS の添字）。
   *           例: 「イオン」なら [1,4,45]。options は空なのでここだけが正解を持つ。
   *
   * choice4 / choice / word のときは空配列。
   */
  panelOrder: number[];
  /** この問題の制限時間（秒）。生成時に既存 scoring.ts の見積りを基に決める */
  timeLimit: number;
  /** 画像URL（元の大問に画像があるとき。無ければ undefined） */
  imageUrl?: string;
  /** Recorded listening audio only; no script, translation or answer hints. */
  audioUrl?: string;
}

