// ルール
// ============================================================

/**
 * 同点だったときの決め方。
 *
 * - time    … 合計解答時間が短い方の勝ち（既定）
 * - sudden  … サドンデス（延長1問。それでも同点なら引き分け）
 * - draw    … 引き分けにする
 */
export type BattleTiebreak = 'time' | 'sudden' | 'draw';

/**
 * 教科ごとの対戦ルール。
 *
 * ★「教科 → ルール」を1か所に集めているのは、運用で後から
 *   数学だけ問題数を減らす・地理だけ時間を伸ばす といった調整を
 *   コードを触らずにできるようにするため。★
 * 既定値はコード内（battleRules.ts）に持ち、Firestore の
 * `battle_rules/{subject}` に同じ形のドキュメントがあればそちらを優先する。
 */
export interface BattleRule {
  scoringVersion?: 2;
  /** 教科ID */
  subject: string;
  /** 対戦を有効にするか。false ならこの教科は対戦の教科選択に出ない */
  enabled: boolean;
  /** 1試合の出題数 */
  questionCount: number;
  /**
   * 1問の制限時間（秒）。
   * null のときは問題ごとの既定（BattleQuestion.timeLimit）を使う。
   * 数値を入れると全問その秒数で固定される（運用で強制したいとき用）。
   */
  timeLimitOverride: number | null;
  /** 正解の基礎点 */
  pointsCorrect: number;
  /** 速さボーナスの上限（残り時間に比例して 0〜この値） */
  pointsSpeedMax: number;
  /** 連続正解ボーナス（3連続以上で 1問につきこの値を加算、上限あり） */
  pointsStreak: number;
  /** 同点時の決め方 */
  tiebreak: BattleTiebreak;
  /**
   * 使う回答形式。ここに無い形式の問題は出題プールから除外される。
   *
   * ★現在の既定は ['choice4', 'choice', 'kana'] である★
   * （＝元データの選択肢をそのまま使う問題＋カタカナの答えをかなで書く問題）。
   * word / panel を入れても、プールにその形式の問題が1件も無いため
   * 出題数は変わらない。理由は BattleAnswerFormat の説明を参照。
   */
  formats: BattleAnswerFormat[];
  /**
   * ★1試合のうち、かな入力（kana）にする問題の割合（0〜1）★
   *
   * 0.3 なら10問中3問がかな入力で、残り7問は選択式になる。
   *
   * ■ なぜ formats とは別に持つのか
   *
   * formats は「使ってよい形式の一覧」であって、比率を表せない。
   * formats から 'kana' を外すと ★かな入力が1問も出ない★ になってしまい、
   * 「みんはや形式をもっと入れたい。ただし全部にはしない」という
   * 要求を表現できない。そこで「使うか」と「どれだけ使うか」を分けた。
   *
   * ■ なぜ全問をかな入力にしないのか
   *
   * かな入力は思い出せないと ★部分点も無く0点★ になる（選択式なら
   * 当てずっぽうでも当たる余地がある）。全問かな入力にすると、
   * まだ覚えていない段階の人が1問も取れず、試合の形にならない。
   *
   * ■ 収録数が足りないときは自動で減る
   *
   * 例えば地理はかな入力が0問なので、0.3 を指定しても全問が選択式になる。
   * 「指定した比率に届かないから試合を組めない」という失敗は起こさない
   * （出題を組み立てる側が、足りない分を他の形式で埋める）。
   */
  kanaShare: number;
  /** 教科選択カードに出す補足（「音声はイヤホン推奨」など）。空文字なら出さない */
  note: string;
}

