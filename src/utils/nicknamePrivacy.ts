/**
 * ===================================================================
 * 全国ランキングでの名前の見せ方（個人情報への配慮）
 * ===================================================================
 *
 * ■ なぜマスキングするのか
 * ニックネーム欄に本名（例: 山田太郎）をそのまま入れている利用者が多く、
 * 全国ランキングは誰でも閲覧できるため、氏名がそのまま全国に公開されて
 * しまう。学校名・学年と組み合わせると個人が特定できてしまうので、
 * 「全国」スコープでは名前の一部を隠して表示する。
 *
 * ■ どこをマスクするか
 *   ・先頭の1文字だけ見せる（「山＊＊＊」）。
 *     名字の1文字目だけなら個人の特定はほぼ不可能だが、
 *     本人や友達は「自分/あの子かも」と認識でき、競争の楽しさは残る。
 *   ・「＊」は最大3個に抑える。文字数をそのまま反映すると
 *     「名前の長さ」という情報まで漏れるし、長いニックネームで行が崩れる。
 *   ・1文字でも必ず「＊」を1個以上付ける（マスクされていること自体を明示する）。
 *
 * ■ マスクしない場所
 *   ・自分自身の行（自分の名前は自分に見えてよい）
 *   ・フレンドランキング（相互承認済みの相手にだけ見える閉じた場なので、
 *     ご要望どおり従来のフルネーム表示を維持する）
 *   ・フレンド・クラス機能そのもの
 */

/**
 * 全国ランキング表示用に名前を部分マスクする。
 * 例: 「山田太郎」→「山＊＊＊」 / 「Ken」→「K＊＊」 / 「あ」→「あ＊」
 *
 * サロゲートペア（絵文字など）を壊さないよう、コードポイント単位で扱う。
 */
export function maskNickname(name: string): string {
  const trimmed = (name || '').trim();
  if (!trimmed) return '＊＊＊';
  const chars = [...trimmed];
  const first = chars[0];
  // 残り文字数ぶんの「＊」。ただし最低1個・最大3個（長さ情報を漏らさない）
  const starCount = Math.min(Math.max(chars.length - 1, 1), 3);
  return first + '＊'.repeat(starCount);
}

/**
 * 「自分の行だけはマスクしない」をまとめた表示用ヘルパー。
 * 全国ランキングの行を map するときにそのまま使う。
 */
export function displayNicknameForNational(name: string, isMe: boolean): string {
  return isMe ? name : maskNickname(name);
}
