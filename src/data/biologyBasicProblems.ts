/**
 * ===================================================================
 * 生物基礎「共通テスト完全対応」問題データ
 * ===================================================================
 *
 * ■ 出題範囲の設計
 *   共通テスト「生物基礎」の学習指導要領の全範囲
 *   （生物の特徴／遺伝子とその働き／体内環境の維持／植生と遷移・
 *     バイオーム／生態系とその保全）を 5 章に分けて網羅する。
 *   定番のセンター・共通テスト対策講義（ここみらい・ひゃくぜみ・
 *   10時間で極める生物基礎 等）が扱う頻出テーマを「範囲として」
 *   すべてカバーするが、問題文・数値・構成はすべて本アプリの
 *   オリジナルであり、既存教材・動画の転載は一切含まない。
 *
 * ■ データ形式
 *   chemistryData / mathIntegralProblems と完全に同じ形。
 *   problem     = { id, category, text, subQuestions[], explanation,
 *                   surroundingKnowledge[], deepDiveTopics[] }
 *   subQuestion = { id, label, type, correctAnswer, acceptedAnswers?,
 *                   correctAnswerRate, detailedExplanation }
 *
 * ■ 出題形式
 *   化学基礎と同じ「文章の空欄（ ア ）（ イ ）を埋める」形式を軸に、
 *   選択式（multiple_choice）と計算問題（short_answer）を織り交ぜる。
 *   用語の表記ゆれ（漢字・かな・別名）は acceptedAnswers で吸収する。
 */

/** 1つの大問。chemistryData の practiceProblems 要素と同形。 */
export type BiologyProblem = {
  id: string;
  category: string;
  text: string;
  subQuestions: any[];
  explanation: string;
  surroundingKnowledge: string[];
  deepDiveTopics: string[];
};

/** 記述式（用語・数値）サブ設問を組み立てる補助 */
const sa = (
  id: string,
  label: string,
  correctAnswer: string,
  theme: string,
  steps: string[],
  acceptedAnswers: string[] = [],
  rate = 70,
) => ({
  id,
  label,
  type: 'short_answer',
  correctAnswer,
  ...(acceptedAnswers.length ? { acceptedAnswers } : {}),
  correctAnswerRate: rate,
  detailedExplanation: { theme, type: '知識再生型', difficulty: 1, steps },
});

/** 選択式サブ設問を組み立てる補助 */
const mc = (
  id: string,
  label: string,
  options: string[],
  correctAnswer: string,
  theme: string,
  steps: string[],
  rate = 75,
) => ({
  id,
  label,
  type: 'multiple_choice',
  options,
  correctAnswer,
  correctAnswerRate: rate,
  detailedExplanation: { theme, type: '演繹型', difficulty: 1, steps },
});

