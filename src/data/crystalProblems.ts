/**
 * 記号選択（(a)・(f) など）の別解パターンを機械的に生成する。
 * 判定エンジン（answerJudge）は全角カッコを半角化しないため、
 * 「(a)・(f)」「（a）（f）」「a,f」「af」などの表記揺れを明示的に許容する。
 */
const letterAnswers = (letters: string[]): string[] => {
  const wraps: ((l: string) => string)[] = [
    (l) => `(${l})`,
    (l) => `（${l}）`,
    (l) => l,
  ];
  const separators = ['・', '、', ',', '，', ' ', ''];
  const out = new Set<string>();
  wraps.forEach((wrap) => {
    separators.forEach((sep) => out.add(letters.map(wrap).join(sep)));
  });
  return Array.from(out);
};

