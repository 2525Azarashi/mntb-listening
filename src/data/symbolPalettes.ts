/**
 * ===================================================================
 * 記号パレットの定義（化学記号パレット／数学記号パレット）
 * ===================================================================
 *
 * ■ なぜ Quiz.tsx から切り出したか
 *   パレットのボタンは1つ1つが「打ち込み表記（value）」と
 *   「組版後の見た目（tex）」の対応を担っている。
 *   ここが崩れると
 *     ・押しても解答が正しく採点されない（value が answerJudge の想定外）
 *     ・ボタン面が KaTeX エラーの赤字になる（tex が組版できない）
 *   という、画面を見ないと気づけない壊れ方をする。
 *   データとして独立させることで、全ボタンを機械的に検証できる
 *   （tests/symbolPalettes.test.ts が KaTeX 組版と value 記法を総当たりする）。
 *
 * ■ ★収録の方針（ご要望）★
 *   「化学式パレットはアルファベットとかまでパレット作ったら練習にならないから
 *     基本は打つのがめんどくさい＋うちづらいものだけつくってくれたらいいよ」
 *
 *   → 入れるもの（キーボードから直接打てない／打つのが面倒な記号だけ）
 *       ・下付き数字（₂ など）… 元素記号のうしろの原子の数
 *       ・上付きの価数（²⁻ など）… 符号と数字の順番も間違えないよう組にする
 *       ・反応式の矢印（→ ⇌ ↑ ↓ ·）
 *       ・指数（×10 と上付き数字）
 *       ・数学の分数・ルート・積分・極限・総和・ギリシャ文字・不等号
 *
 *   → 入れないもの（★練習にならないので意図的に外した★）
 *       ・完成した化学式（H₂O, CO₂, NaCl, H₂SO₄ …）
 *       ・完成したイオン（Na⁺, SO₄²⁻ …）
 *         → 「何と何が結びつくか」を思い出すのが化学の練習そのものなので、
 *           ボタン1つで答えが出てしまうと学習効果が消える。
 *           元素記号は英字キーで普通に打てるため、パレットに置く必要もない。
 *       ・素の英字・数字（x, t, n, C, e, 0-9）や + - = ( ) [ ]
 *         → キーボードから1打で入るので、パレットに置くと
 *           「探す対象」が増えて目的の記号が見つけにくくなるだけ。
 *
 * ■ ★探す時間をゼロにするための構造★
 *   「探すのに時間を取らないようにしたい」というご要望に合わせ、
 *   タブ切り替え（＝どのタブにあるか当てる手間）をやめ、
 *   全グループを1画面に並べたまま表示する（SymbolPalette 側で実装）。
 *   収録数を絞ったのはこのためで、
 *   化学 31 → 4行、数学 16 → 3行に収まり、何も隠れない。
 *   グループ名に①②③の番号を付けているのは、
 *   「上から順に見れば必ず見つかる」ことを目で分かるようにするため。
 *
 * ■ 3層の対応関係（★ここが設計の核★）
 *
 *   ボタン面 (tex)          押すと入る (value)        表示・採点
 *   ─────────────────────────────────────────────────────────────────
 *   \frac{\square}{\square}   "/"                    mathTypeset.toLatex
 *   \ce{\square_2}            "₂"                    → \frac{}{} / \ce{}
 *   \ce{\square^2-}           "²⁻"                   answerJudge が
 *                                                    ₂ / ² を通常数字へ
 *
 *   ★value を LaTeX にしてはいけない★
 *     value は解答欄の文字列にそのまま入る。
 *     採点（answerJudge.normalizeAnswer）も組版（mathTypeset）も
 *     Unicode の上付き・下付きと `^` `/` `√(` という「打ち込み表記」を
 *     前提にしているため、ここに \ce{} や \frac{} を入れると両方壊れる。
 *
 *     なお採点側は「半角でも全角でも、^2 でも ² でも正解」になるよう
 *     answerJudge / answerEquivalence が吸収する。
 *     パレットから入れた ² と、手で打った ^2 は同じ答えとして扱われる。
 */

/**
 * 記号パレットの1ボタン。
 *
 * ■ label / tex / caption の役割分担（ご要望「分かりやすく押しやすく」）
 *   label   … 入力される「打ち込み表記」そのまま（₂, ^, √( …）。
 *             KaTeX が使えない環境でのボタン表記と、内部キーにも使う。
 *   tex     … ★ボタンの顔★。KaTeX（数式は TeX、化学式は mhchem）で組んだ
 *             「実際に解答欄・解説に出るのと同じ字形」を表示する。
 *             生徒がボタン面と出力を見比べて迷わないようにするため、
 *             本文の組版と同じエンジンで描くのが要点。
 *             □（\square）は「ここに数や式が入る」ことを示す穴。
 *   caption … ボタン下の 1〜6 文字の日本語ラベル（「分数」「気体」など）。
 *             記号だけだと意味が分からない項目の取りこぼしを防ぐ。
 *   desc    … 長押し/ホバーの詳しい説明。読み上げ（aria-label）にも使う。
 */
export type PaletteItem = {
  label: string;
  value: string;
  desc: string;
  /** ボタン面に KaTeX で組む LaTeX（省略時は label をそのまま表示） */
  tex?: string;
  /** ボタン下の短い日本語ラベル */
  caption?: string;
  /**
   * 挿入後にキャレットを value の末尾から何文字戻すか。
   * 例: `√()` を入れて caretBack:1 なら、かっこの中で続けて打てる。
   */
  caretBack?: number;
  /** 横に長い項目（グリッドで2列ぶん使う） */
  wide?: boolean;
};

export type PaletteGroup = {
  group: string;
  /** グループの下に出す一行ヒント（使いどころの説明） */
  hint?: string;
  items: PaletteItem[];
};

