/**
 * ===================================================================
 * 化学（発展）の「分野」の表示情報だけを持つファイル
 * ===================================================================
 *
 * 持っているのは次の3件ぶんの ★見出し文字だけ★ で、
 * 問題文・選択肢・解説は1文字も含まない。
 *
 *     理論化学 / 無機化学 / 有機化学
 *
 * -------------------------------------------------------------------
 * ■ なぜ chemistryAdvancedData.ts から出したのか
 * -------------------------------------------------------------------
 * ADVANCED_FIELDS は元々 chemistryAdvancedData.ts の末尾にあった。
 * 中身はただの文字列3件なのに、置き場所が「化学（発展）の問題データ本体」
 * だったため、この3件の文字列を使いたいだけのファイルが
 * ★化学（発展）の全問題を読み込む★ことになっていた。
 *
 * 実際に困っていた場所は2つある。
 *
 *   1. src/App.tsx
 *        import { ADVANCED_FIELDS, type AdvancedFieldId } from './data/chemistryAdvancedData';
 *      使っているのは
 *        ・保存された分野IDが正しいかの確認（ADVANCED_FIELDS.some）
 *        ・見出しに出す分野名（ADVANCED_FIELDS.find(...)?.title）
 *      の2か所だけ。問題データは1問も見ていない。
 *
 *   2. src/components/ChapterSelection.tsx
 *        import { type AdvancedFieldId } from '../data/chemistryAdvancedData';
 *      こちらは★型しか使っていない★。
 *      ところが `import { type X }` という書き方は「値の import 文」なので、
 *      バンドラはモジュールの解決を行い、結果として問題データ本体が
 *      読み込み対象に入ってしまう（`import type { X }` なら完全に消える）。
 *
 * つまり「文字列3件」と「問題データ本体」が同じファイルに同居していたことが、
 * そのまま読み込み量になっていた。責任が違うものは置き場所も分ける。
 *
 * -------------------------------------------------------------------
 * ■ このファイルは何も import しない（★仕様★）
 * -------------------------------------------------------------------
 * 他のファイルを1つも import しないことによって、
 * 「ここを読んでも、そこから先へ辿って問題データに行き着くことはない」
 * が構造として保証される。
 * import を1行足した瞬間にこの保証は消えるので、足さないこと。
 * （何も import していないことは tests/advancedFields.test.ts が検査する）
 *
 * -------------------------------------------------------------------
 * ■ 元の場所からも今までどおり使える
 * -------------------------------------------------------------------
 * chemistryAdvancedData.ts は、この2つをそのまま再エクスポートしている。
 *
 *     export { ADVANCED_FIELDS } from './advancedFields';
 *     export type { AdvancedFieldId } from './advancedFields';
 *
 * そのため
 *   ・既存の呼び出し側（AdvancedFieldSelection.tsx / 各テスト）は
 *     import 文を1文字も変えなくても動く
 *   ・「chemistryAdvancedData から ADVANCED_FIELDS を読む」という
 *     従来の書き方も壊れない
 * という状態を保っている。★機能を消していない。★
 *
 * 軽くしたい側（App.tsx / ChapterSelection.tsx）だけが、
 * このファイルを直接指すように import 元を変えている。
 *
 * -------------------------------------------------------------------
 * ■ ★この分離だけでは読み込み量は減らない（測定結果）★
 * -------------------------------------------------------------------
 * 正直に書いておく。依存グラフを実測すると次のようになった。
 *
 *     切り出し前 : ChapterSelection.tsx が引き込む src/data
 *                  52 ファイル / 2,852,059 バイト
 *     切り出し後 : 53 ファイル / 2,857,738 バイト（★増えている★）
 *
 * 増えたのはこのファイル自身が1つ数えられたからで、
 * 化学（発展）の問題データは相変わらず読み込まれている。
 * 理由は ChapterSelection.tsx がもう1本
 *
 *     import { getPartsOfSubject } from '../data/allChapters';
 *
 * を持っており、allChapters.ts が6教科ぶんのデータ本体を
 * 静的に抱えているためである（＝そちらが本当の原因）。
 *
 * では無意味な変更かというと逆で、こちらを先に外しておかないと
 * allChapters.ts を軽くしても化学（発展）だけは残ってしまう。
 * 実際に allChapters.ts が教科データを抱えていない状態を仮に作って
 * 測ると、この分離込みで
 *
 *     ChapterSelection.tsx : 2,857,738 → 548,826 バイト（−80.8%）
 *     App.tsx              : 3,672,003 → 2,401,870 バイト（−34.6%）
 *
 * まで落ちる。つまりこの分離は ★その効果を出すための前提★ である。
 *
 * 「数字が減っていないから無駄」でも「数字が減ったから完了」でもなく、
 * 原因が2本あって、1本ずつ外している途中という状態。
 *
 * -------------------------------------------------------------------
 * ■ ★vite.config.ts のチャンク例外は「ここには」効かない（実測）★
 * -------------------------------------------------------------------
 * 先生ダッシュボードのときは、ソースを軽くしたあと
 * vite.config.ts の manualChunks に例外を足すことで
 * 「3MB の data チャンクへ送られてしまう」問題を直せた。
 * 同じ手が使えるはずだと考えて、ここでも例外を足して測った。
 *
 *     例外を足す前 : index に 'Theoretical' 0 個 / data に 1 個
 *     例外を足した後: index に 'Theoretical' 0 個 / data に 1 個
 *                     （★ハッシュすら変わらなかった★）
 *
 * 理由は配信物を読んで分かった。index チャンクの先頭には
 *
 *     import{…}from"./data-Dv53rVD0.js"
 *
 * という★静的な import★ が既に入っている。
 * つまり index を読む＝data チャンクも必ず読む状態なので、
 * このファイルを index 側へ移しても、読み込まれる量は1バイトも変わらない。
 *
 * では index→data の辺は誰が作っているのかというと、
 * allChapters.ts が6教科ぶんのデータ本体を静的に抱えていて、
 * それを App.tsx / ChapterSelection.tsx が静的に使っているからである。
 *
 * ★結論★
 *   チャンクの割り方をいじっても、この辺が残っている限り効果は出ない。
 *   直すべきはハブ（allChapters.ts）であって、配信設定ではない。
 *   だから今回は例外を足さずに撤回した（効かない設定を残すと、
 *   次に読む人が「対策済み」と誤解する）。
 *

 * -------------------------------------------------------------------
 * ■ 中身は移動しただけで、1文字も変えていない
 * -------------------------------------------------------------------
 * id / title / latin / description の値・並び順は元のまま。
 * 分野カードの見た目や並びは変わらない。
 * 元と同じであることは tests/advancedFields.test.ts が
 * 実データと突き合わせて検査する。
 */

