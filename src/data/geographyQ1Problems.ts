/** 選択式サブ設問を組み立てる補助（地理はすべて選択式） */
const gq = (
  id: string,
  label: string,
  options: string[],
  correctAnswer: string,
  theme: string,
  steps: string[],
  rate = 60,
) => ({
  id,
  label,
  type: 'multiple_choice',
  options,
  correctAnswer,
  correctAnswerRate: rate,
  detailedExplanation: { theme, type: '資料読解型', difficulty: 2, steps },
});

/** ア〜ウの正誤組合せ選択肢を「本文そのまま」の形で書くための短縮 */
const tf = (a: string, i: string, u: string) => `ア―${a}　イ―${i}　ウ―${u}`;

