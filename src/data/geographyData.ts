/**
 * ===================================================================
 * 地理総合・地理探究　単元データ
 * ===================================================================
 *
 * ■ 構成の考え方
 *   共通テストの地理は「第1問・第2問…」という大問単位で出題されるので、
 *   英語リスニングと同じく
 *     タブ  = 大問（realTitle：'第1問'）
 *     単元  = 回（abstractTitle：'第1回 モンスーンアジアの気候と稲作'）
 *   という2階層にしている。
 *   ChapterSelection の共通処理（realTitle でタブにまとめる／
 *   splitTabTitle が '第1問' を Q1 と読む）にそのまま乗るため、
 *   画面側に地理専用の分岐を足す必要がない。
 *
 * ■ 収録状況
 *   (1) 第1問セット（第1回〜第5回・全25設問）
 *   (2) 共通テスト形式 模擬問題（第1回〜第6回＋予想問題）
 *       1回 = 第1問・第2問・第3問 の3大問なので 21単元・112設問。
 *       問題データは geographyExamProblems.ts（自動生成）にある。
 *
 * ■ ★カード名の末尾に系列を書く理由★
 *   (1) と (2) はどちらも「第1問」タブに入り、しかもどちらも
 *   「第1回 …」で始まるため、カードを並べたときにどちらの系列の
 *   第1回なのか見分けが付かなかった。そこで末尾に
 *     (1) → （単元演習）   (2) → （模試）
 *   と書き分けている。★abstractTitle は画面のカード見出しなので、
 *   ここを変えるとユーザーの見え方が直接変わる★
 *
 * ■ ★配点は表記しない★
 *   ご指示により、大問の見出し・topics・解説のいずれにも
 *   「（配点34点）」のような配点は書かない。生成側（build.py）に
 *   strip_points() と assert_no_points() を置いて機械的に落としている。
 *
 * ■ データ形式
 *   biologyBasicData.ts と完全に同じ形（parts → chapters）。
 */

