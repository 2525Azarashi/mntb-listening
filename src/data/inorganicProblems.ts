/**
 * ===================================================================
 * 化学（発展）・無機化学 演習問題
 * ===================================================================
 *
 * ■ このファイルを作った理由
 *   chemistryAdvancedData.ts の無機化学パート（adv_inorganic）は、
 *   ch() ヘルパーで作られた「章の枠だけ」の状態で、
 *   practiceProblems が全章 [] （空配列）だった。
 *   そのため無機化学は
 *     ・Quiz で解けない
 *     ・Explanation で解説が読めない
 *     ・対戦（バトル）の出題元にもできない
 *       （scripts/verify-authored-battle.mts のチェックBが
 *         「source が実在する小問を指していること」を要求するため、
 *          元の演習問題が無いと手書きバトル問題すら作れない）
 *   という三重の行き止まりになっていた。
 *   ユーザーの指示「無機化学いこう」に従い、まず**演習問題の実体**を書く。
 *
 * ■ 出典・根拠
 *   src/data/chemistryAdvancedTrendData.ts に、無機化学17章ぶんの
 *   examTypes（過去に出た問われ方）と weapons（得点に直結する武器）が
 *   すでに書かれている。ここを一次資料として、
 *   「共通テストで実際に問われた形」だけを問題にした。
 *   勝手な創作知識は入れず、weapons に書かれている事実の範囲で作問している。
 *
 * ■ データ形式
 *   advancedThermoProblems.ts、すなわち chemistryData.ts の practiceProblems と
 *   **完全に同じ形**。だから Quiz.tsx / Explanation.tsx /
 *   ChapterSelection.tsx を一切改造せずに動く。
 *     problem     = { id, category, text, subQuestions[], explanation,
 *                     surroundingKnowledge[], deepDiveTopics[] }
 *     subQuestion = { id, label, type, correctAnswer, options?, acceptedAnswers?,
 *                     gradingCriteria?, correctAnswerRate?, detailedExplanation? }
 *
 * ■ 解説本文の書き方（重要・崩すと解説が1枚の壁になる）
 *   utils/explanationFormat.ts の enhanceExplanation() が
 *   「解答カード → 小問ごとのアコーディオン」へ自動整形する。
 *   切り分けさせるため、解説本文は
 *     ・小問の見出し（（1）・（ア）・① など）を必ず**行頭**に置く
 *     ・見出しの表記を subQuestion.label の先頭と一致させる
 *   というルールで書いている。
 *
 * ■ 表記ルール（scripts/lint-chem.mjs と textFormatter.tsx に合わせる）
 *   ・記号 = + - / < > % [ ] は半角。数字・英字も半角。
 *   ・単位のスラッシュ（kJ/mol・mol/L・g/cm³）は半角のままでよい。
 *   ・化学式の数字は下付き（H₂O・H₂SO₄）で書く。
 *   ・下線タグは使わない（禁止スタイル）。「STEP」も使わない。
 */

/** 1つの大問。advancedThermoProblems.ts の AdvancedProblem と同形。 */
/**
 * 小問の出題形式。
 *
 * ■ なぜ文字列ではなくユニオン型にしたか
 *   もともと subQuestions は any[] だったため、Quiz.tsx が描けない type を
 *   書いても TypeScript が何も言わず、テストを実行するまで気づけなかった。
 *   実際にこのファイルへ a7_7 を書いたとき、
 *   'multiple-choice'（正しくは 'multiple_choice'）や
 *   存在しない 'multiple-select' を書いてしまい、
 *   tsc は通ったのに vitest で初めて発覚した。
 *   画面に何も表示されない不具合になるので、型で入口を閉じる。
 *
 *   ここに並べた3つは tests/inorganicProblems.test.ts の supported と
 *   同じ集合でなければならない。増やすときは Quiz.tsx の描画分岐と
 *   テストの supported も必ず同時に直すこと。
 */
export type InorganicSubQuestionType = 'short_answer' | 'multiple_choice' | 'descriptive';

/** 1つの小問。 */
export type InorganicSubQuestion = {
  id: string;
  label: string;
  type: InorganicSubQuestionType;
  correctAnswer: string;
  /** 表記ゆれを許す別解（short_answer で使う）。 */
  acceptedAnswers?: string[];
  /** multiple_choice の選択肢。 */
  options?: string[];
  /**
   * descriptive の採点観点。
   * テストが2件以上を要求している。1件だと「どちらか書けていれば丸」に
   * なってしまい、自己採点の基準がぶれるため。
   */
  gradingCriteria?: string[];
  correctAnswerRate?: number;
  /**
   * 小問ごとの追加解説。
   *
   * ■ なぜ2つの形を許しているか
   *   既存の章は「テーマ・型・手順」に分けた構造つきの形で書いてあり、
   *   あとから書いた章は地の文で書いてある。どちらも実際に動いているので、
   *   片方に寄せて既存データを書き換えるのは危険（表示崩れの原因になる）。
   *   そこで型は実態どおり両方を許し、
   *   「どちらの形でもよい」ことを明示している。
   */
  detailedExplanation?:
    | string
    | {
        theme: string;
        type: string;
        difficulty?: number;
        steps: string[];
      };
};

export type InorganicProblem = {
  id: string;
  category: string;
  text: string;
  subQuestions: InorganicSubQuestion[];
  explanation: string;
  surroundingKnowledge: string[];
  deepDiveTopics: string[];
};

