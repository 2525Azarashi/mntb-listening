/**
 * ===================================================================
 * 「章に大問が何問入っているか」を数えるための共通関数
 * ===================================================================
 *
 * アプリの中では「1つの章に含まれる大問の数」を、
 *
 *     (c.miniTest?.length || 0) + (c.practiceProblems?.length || 0)
 *
 * という式で数えている箇所が、教科データ側と画面側を合わせて10か所あった。
 * 書き方は少しずつ違うものの（足す順番が逆、`(c.miniTest || []).length` 形式）、
 * すべて「ミニテストの問題数 ＋ 演習の問題数」という同じ意味の式である。
 *
 * -------------------------------------------------------------------
 * ■ なぜ1か所にまとめるのか
 * -------------------------------------------------------------------
 * 数え方そのものは「この2つを足す」という業務上の決めごとで、
 * 今後もし「模試（mockExam）も大問に数える」といった変更が入ると、
 * 10か所すべてを漏れなく直さなければならない。1か所でも直し忘れると、
 * 「進捗の分母」と「科目カードの収録数」がズレて、
 * ユーザーから見て 3/174 のはずが 3/180 になるような食い違いが起きる。
 *
 * そこで数え方だけをこのファイルに集約した。
 * 表示も計算結果も今までとまったく同じで、変えたのは「どこに書いてあるか」だけ。
 *
 * -------------------------------------------------------------------
 * ■ なぜ utils ではなく data に置くのか
 * -------------------------------------------------------------------
 * この関数は教科データ（src/data/*.ts）の中からも呼ぶ。
 * src/data から src/utils を参照する向きは、ビルド時のチャンク分割で
 * 循環が発生する原因になっているため（docs/BUILD.md 4章）、
 * これ以上増やさないように data 側へ置いている。
 *
 * また、このファイルは他のどのファイルも import しない「葉」にしてある。
 * 教科データ側から呼んでも循環しないようにするため。
 */

/**
 * 章に入っている大問の数（ミニテスト ＋ 演習）。
 *
 * 章オブジェクトの形は教科ごとに少しずつ違う（リスニングには marks があるなど）ので、
 * 引数の型は「miniTest と practiceProblems があるかもしれないもの」だけを求める。
 * どちらも無い章（まだ問題を用意していない単元）は 0 を返す。
 */
export function countChapterProblems(chapter: {
  miniTest?: unknown[] | null;
  practiceProblems?: unknown[] | null;
} | null | undefined): number {
  if (!chapter) return 0;
  return (chapter.miniTest?.length || 0) + (chapter.practiceProblems?.length || 0);
}

/**
 * 章の配列に入っている大問の合計数。
 *
 * `chapters.reduce((sum, c) => sum + …, 0)` を各所で書いていたぶんをまとめたもの。
 */
export function countProblemsInChapters(
  chapters: ReadonlyArray<{
    miniTest?: unknown[] | null;
    practiceProblems?: unknown[] | null;
  }> | null | undefined,
): number {
  if (!chapters) return 0;
  return chapters.reduce((sum, chapter) => sum + countChapterProblems(chapter), 0);
}
