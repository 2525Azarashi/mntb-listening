/**
 * TOEIC Part 5 解説の追加項目（任意）の型（2026-10-29）
 *
 * 問題データ（toeicPart5RoundNN.ts の問題文・選択肢・正解・既存の解説）は1文字も変えずに、
 * 別ファイル（toeicPart5NotesRoundNN.ts）へ「着眼点・ポイント・TOEICでのコツ・手がかり」を足す。
 * どれも空でよい。空の項目は画面に見出しごと出さない。
 *
 * 役割を混ぜない（docs/TOEIC_P5_GLOSSARY.md の決まり）
 *   h   … 着眼点：最初にどこを見るか（1〜2文）
 *   r   … ポイント：どう決まるか。次の問題にも使える一般化したルール（1〜2文）
 *   tip … TOEICでのコツ：実戦での使い方（1〜2文。断定・効果の約束は書かない）
 *   cues… 手がかり：問題文の中で根拠になる語句と、それに対応する「正解の理由」の中の語句。
 *         p … 問題文の中の語句（英語のまま。空所にはかからない）
 *         o … 同じ語句が問題文に2回以上あるとき、何回目か（1始まり。省略＝1回目）
 *         w … 「正解の理由」の中で対応する語句（省略＝p と同じ文字列）。
 *             日本語で書かれた理由（例：「領収書と経理部が手がかり」）に対応させるときに使う。
 *             このときは和訳にも同じ語句があること（問題文のその部分の訳であることの確かめ）。
 *         画面では問題文・解説の再掲・正解の理由の3か所に、同じ番号の黄色いマーカーを引く。
 */
export interface ToeicCue {
  p: string;
  o?: number;
  w?: string;
}

export interface ToeicP5Note {
  h?: string;
  r?: string;
  tip?: string;
  cues?: ToeicCue[];
}
