export interface KyotsuAudioTrack {
  /** 問番号（'01' や '18-21'）。ファイル名にも使う */
  q: string;
  /** 大問（例：第1問A）。プレーヤーの見出し */
  part: string;
  /** 画面に出す名前（例：第1問A 問1） */
  label: string;
  /** public/ からのパス */
  file: string;
  /** 秒（目安・実物と±1秒） */
  sec: number;
  /** 2回読みか */
  twice: boolean;
}

/** '01' → 問1、'18-21' → 問18〜21 */
export function kyotsuAudioLabel(q: string): string {
  const [a, b] = q.split('-').map(Number);
  return b ? `問${a}〜${b}` : `問${a}`;
}

