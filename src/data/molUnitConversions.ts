/**
 * ===================================================================
 * 物質量（mol）計算問題の「単位変換」解説データ
 * ===================================================================
 *
 * ■ 目的
 * まとめプリントの★単位変換の図★（mol をハブにした乗り換え路線図）を、
 * 物質量がからむすべての計算問題の解説に一貫して適用する。
 *
 * ■ 単位変換の図（この1枚だけで化学基礎の計算は全部解ける）
 *
 *            ÷ 6.0×10²³              ÷ モル質量 M [g/mol]
 *   ［個数］ ───────────→ ［mol］ ←─────────────── ［質量 g］
 *            ←─────────           ───────────────→
 *            × 6.0×10²³              × モル質量 M [g/mol]
 *                                │
 *                    ÷ 22.4 L/mol │ × 22.4 L/mol   （標準状態の気体だけ）
 *                                ↓
 *                    ［標準状態の体積 L］
 *
 *   ・体積[L] ←（× 密度 d）→ 質量[g]           … 液体・固体はこの橋を使う
 *   ・mol ←（÷ / × モル濃度 c [mol/L]）→ 溶液の体積[L] … 溶液の計算
 *
 * ■ たった2つのルール
 *   ルール1：mol へ「向かう」ときは ÷（割る）
 *   ルール2：mol から「離れる」ときは ×（掛ける）
 *   → 公式を4つも5つも覚える必要はない。図の矢印をたどるだけ。
 *
 * ■ 換算係数（分数）で書くとミスが消える
 *   ÷ 44 g/mol は「× (1 mol / 44 g)」と書ける。こう書くと、
 *   前の「g」と分母の「g」が約分され、残る単位が「mol」になることが目で見える。
 *   ★最後に残った単位が答えの単位と一致していれば、計算の筋道は正しい★
 *
 * ■ なぜ問題データ側ではなくここに置くのか
 * chemistryData.ts の explanation 文字列を直接書き換えると、
 *   ・整形エンジン（explanationFormat.ts）が作る【解 答】ブロックと重複する
 *   ・既存の「詳しい解説」や出題傾向ボックスを壊す危険がある
 * ため、「単位変換の道順」だけを独立したデータとして持ち、
 * 整形エンジンが解答の直後に差し込む方式にした。既存の解説はそのまま残る。
 */

