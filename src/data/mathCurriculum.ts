export function buildCurriculumProblems(unit: MathCurriculumUnit): MathProblem[] {
  return unit.exercises.map((exercise, index) => {
    const id = `p_${unit.id}_${index + 1}`;
    // Rotate positions deterministically; source and generated battle data stay identical.
    const options = exercise.wrong ? [...exercise.wrong] as string[] : [];
    if (exercise.wrong) options.splice((index + unit.id.length) % 4, 0, exercise.answer);
    const sub = exercise.wrong
      ? { id: `${id}_answer`, label: '答えを選びなさい。', type: 'multiple_choice', options, correctAnswer: exercise.answer }
      : sq(`${id}_answer`, '答えを入力しなさい。', exercise.answer, exercise.accepted);
    return {
      id, category: `${unit.title}・${exercise.wrong ? '確認' : '入力演習'}${index + 1}`,
      text: exercise.prompt,
      subQuestions: [{ ...sub, explanation: exercise.explanation }],
      explanation: exercise.explanation,
      surroundingKnowledge: unit.lesson,
      deepDiveTopics: [unit.caution],
    };
  });
}
