/**
 * ===================================================================
 * 指導テンプレート・単位変換の「データの形」
 * ===================================================================
 *
 * -------------------------------------------------------------------
 * ■ なぜ型だけを src/data 側に置くのか
 * -------------------------------------------------------------------
 * これらの型はもともと utils/explanationFormat.ts で定義されていた。
 * しかし実際に「この形のデータを持っている」のは
 *
 *     data/unitTeaching.ts        （単元ごとの指導テンプレート）
 *     data/molUnitConversions.ts  （問題ごとの単位変換ルート）
 *
 * という src/data 側のファイルである。そのため
 *
 *     data/unitTeaching.ts  →  utils/explanationFormat.ts
 *
 * という「データ層が整形ユーティリティを参照する」向きの import が
 * 発生していた。型が欲しいだけなのに、74KB の整形ロジック一式と
 * 結びついてしまうのは筋が悪い。
 *
 * 型の置き場をデータ側に移すことで、
 *
 *   - データファイルは「自分の形の定義」だけを見ればよくなる
 *   - 整形ロジック（utils）を触っても、データ側の型は影響を受けない
 *
 * という分離ができる。依存の向きも data -> utils から data 内で完結する。
 *
 * -------------------------------------------------------------------
 * ■ 互換性について
 * -------------------------------------------------------------------
 * utils/explanationFormat.ts はこれらの型をそのまま再エクスポートしている。
 * そのため `import type { UnitTeaching } from '../utils/explanationFormat'`
 * と書いている既存コードは**変更不要**でそのまま動く。
 *
 * また型は TypeScript のコンパイル時に消えるため、
 * この分離によって**実行されるコードは一切変わらない**。
 */

/** 思考手順の1ステップ */
export interface ThinkingStep {
  /** ステップの見出し（「〇〇を確認する」のように動詞で終える） */
  title: string;
  /** なぜそう考えるのか・着眼点の短い説明 */
  detail: string;
}

/** 単元別の「共通テスト出題傾向」ボックスの中身 */
export interface TrendInsight {
  /** 出典（例：「2021年 共通テスト 本試験 第1問 問5」） */
  sources: string[];
  /** 過去問で実際に問われた要素 */
  asked: string[];
  /** 頻出のひっかけ */
  traps: string[];
  /** 問題と傾向をリンクさせた実践的アドバイス */
  advice: string;
}

/** 単元（章）ごとの指導テンプレート */
export interface UnitTeaching {
  /** この単元の問題を解くときの標準的な思考手順 */
  steps: ThinkingStep[];
  /** 出題傾向ボックスの内容 */
  trend: TrendInsight;
}

// -------------------------------------------------------------------
// 単位変換（まとめプリントの「単位変換の図」）
// -------------------------------------------------------------------

/**
 * 単位変換の1ホップ（図の矢印1本ぶん）。
 *
 * 「単位変換の図」では、mol をハブにして
 *   個数 ←（÷ / × 6.0×10²³）→ mol ←（÷ / × M）→ 質量[g]
 *                              mol ←（÷ / × 22.4）→ 標準状態の体積[L]
 * という橋が架かっている。その1本を表す。
 */
export interface ConversionHop {
  /** 矢印に書く換算（例：「÷ 44 g/mol」「× 22.4 L/mol」「× 2（係数比）」） */
  arrow: string;
  /** 変換後に到達する単位（例：「mol」「L」「g」「個」） */
  to: string;
}

/**
 * 1問ぶんの「単位変換による解き方」。
 *
 * 物質量（mol）がからむ計算問題は、公式の暗記ではなく
 * 「スタートの単位 → mol → ゴールの単位」という一本道の乗り換えで必ず解ける。
 * その道順をデータとして持ち、解説の先頭に図と同じ形で提示する。
 */
export interface UnitConversionWalk {
  /** スタートの量（例：「88 g（二酸化炭素の質量）」） */
  start: string;
  /** スタートの単位（ルート図の左端。例：「g」） */
  startUnit: string;
  /** ゴール（例：「標準状態の体積 [L]」） */
  goal: string;
  /** mol を経由してゴールへ向かう矢印の並び */
  route: ConversionHop[];
  /** ①②③ の思考手順（見出し＋理由・着眼点の2段構成） */
  steps: ThinkingStep[];
  /** 換算をひと続きに書いた式（省略可） */
  oneLine?: string[];
  /** 単位の約分などによる検算コメント（省略可） */
  check?: string;
}
